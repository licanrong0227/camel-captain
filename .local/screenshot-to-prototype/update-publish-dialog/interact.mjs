import path from 'node:path';
import { pathToFileURL } from 'node:url';
const pwPath = path.join(process.env.USERPROFILE, '.cache', 'axure-extractor', 'node_modules', 'playwright', 'index.mjs');
const { chromium } = await import(pathToFileURL(pwPath).href);
const browser = await chromium.launch({ args: ['--allow-file-access-from-files', '--no-sandbox'] });
const page = await browser.newPage({ viewport: { width: 1280, height: 800 } });
await page.goto('http://localhost:53817/?projectId=make-project-2&p=update-publish-dialog');
await page.waitForTimeout(6000);
const frame = page.frames().find(f => f !== page.mainFrame() && f.url().includes('53817')) || page.mainFrame();
const frames = page.frames();
console.log('frames:', frames.map(f => f.url()).join('\n'));
const target = frames.find(f => f !== page.mainFrame()) || page.mainFrame();
await target.locator('.up-footer-check').click();
await target.locator('.up-radio', { hasText: '定时发布' }).click();
await target.locator('.up-checkbox', ).first().click();
await target.locator('.up-checkbox').first().click();
await page.waitForTimeout(500);
await page.screenshot({ path: '.local/screenshot-to-prototype/update-publish-dialog/react-interact.png' });
const disabled = await target.locator('.up-number__input').isDisabled();
const numClass = await target.locator('.up-number').getAttribute('class');
console.log('input disabled after check:', disabled, 'class:', numClass);
await browser.close();
